export type Dictionary = (typeof dictionaries)[Locale];

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

// Kept as a standalone function rather than a Dictionary method: the
// Dictionary object gets passed as a prop into several Client Components,
// and a function anywhere in that object graph breaks serialization across
// the server/client boundary — even for components that never call it.
export function stepOfLabel(locale: Locale, step: number, total: number): string {
  return locale === "es" ? `Paso ${step} de ${total}` : `Step ${step} of ${total}`;
}
